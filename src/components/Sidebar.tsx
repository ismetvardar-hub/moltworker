function allowedItem(
  id: string,
  allowedPages: string[],
  modules: Set<string>,
  activeBrand: AuthBrand | undefined,
) {
  if (!allowedPages.includes(id)) return false;
  if (!activeBrand || ALWAYS_VISIBLE.has(id)) return true;
  return modules.has(id);
}

